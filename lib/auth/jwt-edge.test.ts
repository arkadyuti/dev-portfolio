// @vitest-environment node
// jwt-edge uses TextEncoder; jose's internal `instanceof Uint8Array` check fails
// under jsdom's cross-realm polyfill, so this file runs in the node environment
// (matching the real Edge runtime, which has a native TextEncoder).
import { describe, it, expect } from 'vitest'
import jwt from 'jsonwebtoken'

import { verifyAccessToken as edgeVerifyAccessToken } from '@/lib/auth/jwt-edge'
import { generateAccessToken, generateRefreshToken } from '@/lib/auth/jwt-node'

// ── helpers ────────────────────────────────────────────────────────────────

const ACCESS_SECRET = process.env.JWT_ACCESS_SECRET!

const BASE_PAYLOAD = {
  userId: 'user-edge-456',
  role: 'editor',
  sessionId: 'session-xyz',
}

function signWithExpiry(payload: object, secret: string, expiresInSec: number): string {
  return jwt.sign(payload, secret, {
    algorithm: 'HS256',
    expiresIn: expiresInSec,
  })
}

// ── happy-path: cross-compatibility ───────────────────────────────────────

describe('jwt-edge verifyAccessToken — cross-compatibility with jwt-node', () => {
  it('verifies a token generated by generateAccessToken (node)', async () => {
    const token = generateAccessToken(BASE_PAYLOAD)
    const result = await edgeVerifyAccessToken(token)
    expect(result).not.toBeNull()
    expect(result?.userId).toBe(BASE_PAYLOAD.userId)
    expect(result?.role).toBe(BASE_PAYLOAD.role)
    expect(result?.sessionId).toBe(BASE_PAYLOAD.sessionId)
  })

  it('returns a payload with version field v=1', async () => {
    const token = generateAccessToken(BASE_PAYLOAD)
    const result = await edgeVerifyAccessToken(token)
    expect(result?.v).toBe(1)
  })

  it('verifies token for each allowed role', async () => {
    for (const role of ['admin', 'editor', 'viewer'] as const) {
      const token = generateAccessToken({ ...BASE_PAYLOAD, role })
      const result = await edgeVerifyAccessToken(token)
      expect(result?.role).toBe(role)
    }
  })
})

// ── rejection cases ────────────────────────────────────────────────────────

describe('jwt-edge verifyAccessToken — rejections', () => {
  it('returns null for an expired token', async () => {
    const token = signWithExpiry({ ...BASE_PAYLOAD, v: 1 }, ACCESS_SECRET, -1)
    const result = await edgeVerifyAccessToken(token)
    expect(result).toBeNull()
  })

  it('returns null for a tampered token', async () => {
    const token = generateAccessToken(BASE_PAYLOAD)
    const tampered = token.slice(0, -6) + 'AAAAAA'
    const result = await edgeVerifyAccessToken(tampered)
    expect(result).toBeNull()
  })

  it('returns null for a token signed with the wrong secret', async () => {
    const token = jwt.sign({ ...BASE_PAYLOAD, v: 1 }, 'completely-wrong-secret', {
      algorithm: 'HS256',
      expiresIn: '15m',
    })
    const result = await edgeVerifyAccessToken(token)
    expect(result).toBeNull()
  })

  it('returns null for a refresh token (wrong secret)', async () => {
    const token = generateRefreshToken(BASE_PAYLOAD)
    const result = await edgeVerifyAccessToken(token)
    expect(result).toBeNull()
  })

  it('returns null for an invalid role', async () => {
    const token = jwt.sign(
      { ...BASE_PAYLOAD, role: 'root', v: 1 },
      ACCESS_SECRET,
      { algorithm: 'HS256', expiresIn: '15m' }
    )
    const result = await edgeVerifyAccessToken(token)
    expect(result).toBeNull()
  })

  it('returns null when userId is missing', async () => {
    const { userId: _u, ...withoutUserId } = BASE_PAYLOAD
    const token = jwt.sign({ ...withoutUserId, v: 1 }, ACCESS_SECRET, {
      algorithm: 'HS256',
      expiresIn: '15m',
    })
    const result = await edgeVerifyAccessToken(token)
    expect(result).toBeNull()
  })

  it('returns null when sessionId is missing', async () => {
    const { sessionId: _s, ...withoutSession } = BASE_PAYLOAD
    const token = jwt.sign({ ...withoutSession, v: 1 }, ACCESS_SECRET, {
      algorithm: 'HS256',
      expiresIn: '15m',
    })
    const result = await edgeVerifyAccessToken(token)
    expect(result).toBeNull()
  })

  it('returns null for an empty string', async () => {
    const result = await edgeVerifyAccessToken('')
    expect(result).toBeNull()
  })

  it('returns null for a non-JWT string', async () => {
    const result = await edgeVerifyAccessToken('not.a.jwt')
    expect(result).toBeNull()
  })

  it('returns null for a token whose payload fields have wrong types', async () => {
    const token = jwt.sign(
      { userId: 123, role: true, sessionId: null, v: 1 },
      ACCESS_SECRET,
      { algorithm: 'HS256', expiresIn: '15m' }
    )
    const result = await edgeVerifyAccessToken(token)
    expect(result).toBeNull()
  })
})

// ── payload shape ──────────────────────────────────────────────────────────

describe('jwt-edge verifyAccessToken — payload shape', () => {
  it('returned payload includes iat and exp', async () => {
    const token = generateAccessToken(BASE_PAYLOAD)
    const result = await edgeVerifyAccessToken(token)
    expect(typeof result?.iat).toBe('number')
    expect(typeof result?.exp).toBe('number')
  })

  it('exp is approximately 15 minutes from now', async () => {
    const before = Math.floor(Date.now() / 1000)
    const token = generateAccessToken(BASE_PAYLOAD)
    const after = Math.floor(Date.now() / 1000)
    const result = await edgeVerifyAccessToken(token)
    expect(result?.exp!).toBeGreaterThanOrEqual(before + 900 - 2)
    expect(result?.exp!).toBeLessThanOrEqual(after + 900 + 2)
  })
})
